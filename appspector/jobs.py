"""Job specs, batch generation, submission, records and connections.

A JobSpec says what to run (a program from the site, or a directory and
command line), with what arguments, how many PEs, nodes and processes.
``start(site, spec)`` turns it into a running job: a generated batch script
submitted over ssh for a Slurm site, or a local process. ``connect(job)``
brings up the transport (the ssh port forward) and returns host and port
for ccsio and the viewer. Every job is recorded in ~/.appspector/jobs.json
so a later shell, or another machine with the same file, can attach.

Authentication: unless the site says ``auth = no`` or the spec says
``auth=False``, every job gets a fresh CCS key. The key file (``0 KEY``, the
level-0 line ``++server-auth`` reads) is written next to the batch script
with mode 600, ``++server-auth <file>`` is appended to the command, and the
key string is kept in the job record so ``view`` and ``server()`` can use it
without asking. The handshake authenticates each request; it does not
encrypt the traffic.
"""

import json
import os
import secrets
import subprocess
import time
from dataclasses import asdict, dataclass, field
from typing import Optional

from . import launch as L
from .sites import Site

JOBS_FILE = os.path.expanduser("~/.appspector/jobs.json")

SLURM_TEMPLATE = """#!/bin/bash
#SBATCH -J {jobname}
#SBATCH -A {account}
#SBATCH -p {partition}
#SBATCH -N {nodes}
#SBATCH --ntasks={procs}
#SBATCH --cpus-per-task={cores_per_proc}
{memline}#SBATCH -t {walltime}
#SBATCH -o {out}
# generated by appspector for {program} on {site} at {when}
source {env}
ulimit -c 0
unset SLURM_CPUS_PER_TASK
export SLURM_CPU_BIND=none SRUN_CPU_BIND=none
cd {directory}
{launcher} {command}
"""


@dataclass
class JobSpec:
    program: str = ""            # name in the site's [programs], or "" with directory+command
    args: str = ""
    pes: int = 0                 # 0: site default
    nodes: int = 0
    procs_per_node: int = 0
    walltime: str = ""
    mem: str = ""
    port: int = 0
    directory: str = ""          # explicit program (overrides .program)
    command: str = ""
    auth: Optional[bool] = None  # None: the site's setting

    def wants_auth(self, site: Site):
        return site.auth if self.auth is None else self.auth

    def resolve(self, site: Site, stamp=None):
        """Fill defaults from the site; returns (directory, command, values).
        ``stamp`` names this run's files (key file); unknown before ``start``,
        shown as <stamp> by ``show`` and ``script``."""
        pes = self.pes or site.default_pes
        nodes = self.nodes or site.default_nodes
        ppn = self.procs_per_node or site.default_procs_per_node
        procs = nodes * ppn
        # ask for the cores the PEs will use (PEs per process), not the whole
        # node share: on shared partitions a whole-node request can queue for
        # hours while a small one starts at once
        import math
        if pes < procs:
            raise ValueError("%d PEs over %d processes (%d node(s) x %d per node): every process needs at "
                             "least one PE, so raise 'pes' to %d or more, or lower 'nodes'/'ppn'"
                             % (pes, procs, nodes, ppn, procs))
        if pes % procs:
            # Charm++ splits the PEs over the processes; an uneven split works
            # but is rarely what was meant
            import warnings
            warnings.warn("%d PEs do not divide evenly over %d processes" % (pes, procs))
        pes_per_proc = max(1, math.ceil(pes / max(1, procs)))
        cores_per_proc = min(max(1, site.cores_per_node // max(1, ppn)), pes_per_proc) if site.scheduler != "local" else 1
        port = self.port or site.port
        if self.command:
            directory, command = self.directory or ".", self.command
        else:
            if self.program not in site.programs:
                raise KeyError("site %s has no program '%s' (known: %s)"
                               % (site.name, self.program, ", ".join(sorted(site.programs)) or "none"))
            p = site.programs[self.program]
            directory, command = p.directory, p.command
        keyfile = ""
        if self.wants_auth(site):
            keyfile = key_path(site, self.program or "job", stamp or "<stamp>")
        values = dict(args=self.args, pes=pes, port=port, procs=procs, cores_per_proc=cores_per_proc,
                      nodes=nodes, walltime=self.walltime or site.walltime, mem=self.mem or site.mem,
                      keyfile=keyfile)
        command = site.expand(command, **values)
        if keyfile and "++server-auth" not in command:
            command += " ++server-auth " + keyfile
        directory = site.expand(directory, **values)
        return directory, command, values


@dataclass
class Job:
    id: str                      # Slurm job id, or "local-<pid>"
    site: str
    program: str
    args: str
    pes: int
    port: int
    out: str                     # output file (remote path for slurm)
    submitted: float
    state: str = "submitted"     # submitted | running | up | ended | cancelled
    node: str = ""
    ip: str = ""
    forward: str = ""            # local:node:remote when registered
    script: str = ""
    pid: int = 0                 # local jobs
    viewer_args: str = ""        # from the program entry
    key: str = ""                # the ++server-auth key string ("" when the job runs without auth)

    def label(self):
        return "%s %s%s on %s (%d PEs, port %d%s) %s" % (
            self.id, self.program, " " + self.args if self.args else "", self.site, self.pes, self.port,
            ", auth" if self.key else "", self.state)


# -- keys ------------------------------------------------------------------

KEY_DIGITS = 32


def new_key():
    """A fresh key string for ++server-auth. The server reads the string as
    16 DECIMAL digit pairs (sscanf "%d" in CCS_AUTH_makeSecretKey), so the key
    is 32 decimal digits: 100^16, about 106 bits."""
    return "".join(secrets.choice("0123456789") for _ in range(KEY_DIGITS))


def key_file_text(key):
    """The ++server-auth file: one line, security level 0 and the key."""
    return "0 %s\n" % key


def key_path(site, program, stamp):
    if site.scheduler == "local":
        return os.path.join(site.work, "%s-%s.key" % (program, stamp))
    return "%s/jobs/%s-%s.key" % (site.work, program, stamp)


# -- records ---------------------------------------------------------------

def load_jobs():
    try:
        with open(JOBS_FILE) as f:
            return [Job(**j) for j in json.load(f)]
    except (OSError, ValueError):
        return []


def save_jobs(jobs):
    """Write the records; the file holds job keys, so it is mode 600."""
    os.makedirs(os.path.dirname(JOBS_FILE), exist_ok=True)
    fd = os.open(JOBS_FILE, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump([asdict(j) for j in jobs], f, indent=1)
    try:
        os.chmod(JOBS_FILE, 0o600)      # an older, world-readable file
    except OSError:
        pass


def record(job):
    jobs = [j for j in load_jobs() if j.id != job.id]
    jobs.append(job)
    save_jobs(jobs[-50:])


def find_job(job_id):
    for j in load_jobs():
        if j.id == str(job_id):
            return j
    return None


# -- starting ----------------------------------------------------------------

def render_batch(site, spec, jobname="appspector", stamp=None):
    directory, command, v = spec.resolve(site, stamp)
    out = "%s/jobs/%s-%%j.out" % (site.work, spec.program or "job")
    script = SLURM_TEMPLATE.format(
        jobname=jobname, account=site.account, partition=site.partition, nodes=v["nodes"], procs=v["procs"],
        cores_per_proc=v["cores_per_proc"], memline=("#SBATCH --mem=%s\n" % v["mem"]) if v["mem"] else "",
        walltime=v["walltime"], out=out,
        program=spec.program or command.split()[0], site=site.name, when=time.strftime("%Y-%m-%d %H:%M:%S"),
        env=site.env, directory=directory, launcher=site.expand(site.launcher, **v), command=command)
    return script, out, v


def start(site, spec, log=print):
    """Submit (slurm) or launch (local). Returns the recorded Job."""
    if site.scheduler == "local":
        return _start_local(site, spec, log)
    if site.scheduler != "slurm":
        raise L.LaunchError("scheduler '%s' is not supported yet" % site.scheduler)
    if not L.reachable(site.ssh):
        raise L.LaunchError("cannot ssh to '%s' non-interactively: open a control master with `ssh %s` "
                            "(Duo sites) or set up key authentication, then retry" % (site.ssh, site.ssh))
    stamp = time.strftime("%Y%m%d-%H%M%S")
    script, out_tmpl, v = render_batch(site, spec, jobname="as-" + (spec.program or "job")[:12], stamp=stamp)
    remote_script = "%s/jobs/%s-%s.sbatch" % (site.work, spec.program or "job", stamp)
    key = new_key() if v["keyfile"] else ""
    parts = ["mkdir -p %s/jobs" % site.work]
    if key:
        # the key file goes in before the batch script is submitted. Created
        # empty, then chmod 600, then written: a umask does not help on a
        # directory with a default ACL (Anvil's project space), chmod does.
        kf = v["keyfile"]
        parts.append("touch %s && chmod 600 %s && cat > %s <<'APPSPECTOR_EOF'\n%sAPPSPECTOR_EOF"
                     % (kf, kf, kf, key_file_text(key)))
    parts.append("cat > %s <<'APPSPECTOR_EOF'\n%sAPPSPECTOR_EOF" % (remote_script, script))
    L.ssh(site.ssh, " && ".join(parts))
    job_id = L.submit(site.ssh, remote_script)
    job = Job(id=job_id, site=site.name, program=spec.program or spec.command, args=spec.args, pes=v["pes"],
              port=v["port"], out=out_tmpl.replace("%j", job_id), submitted=time.time(), script=remote_script,
              viewer_args=site.programs[spec.program].viewer_args if spec.program in site.programs else "",
              key=key)
    record(job)
    log("submitted job %s on %s: %s" % (job_id, site.name, job.out))
    return job


def write_key_file(path, key):
    """Write a local ++server-auth file, readable by this user only."""
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(key_file_text(key))
    os.chmod(path, 0o600)


def _start_local(site, spec, log):
    stamp = time.strftime("%Y%m%d-%H%M%S")
    directory, command, v = spec.resolve(site, stamp)
    os.makedirs(site.work, exist_ok=True)
    out = os.path.join(site.work, "%s-%s.out" % (spec.program or "job", stamp))
    exe = command.split()[0]
    if not os.path.exists(os.path.join(directory, exe)):
        raise L.LaunchError("no %s in %s (built?)" % (exe, directory))
    key = ""
    if v["keyfile"]:
        key = new_key()
        write_key_file(v["keyfile"], key)
    with open(out, "w") as f:
        proc = subprocess.Popen(command, shell=True, cwd=directory, stdout=f, stderr=subprocess.STDOUT)
    job = Job(id="local-%d" % proc.pid, site=site.name, program=spec.program or spec.command, args=spec.args,
              pes=v["pes"], port=v["port"], out=out, submitted=time.time(), pid=proc.pid, state="running",
              viewer_args=site.programs[spec.program].viewer_args if spec.program in site.programs else "",
              key=key)
    record(job)
    log("started %s (pid %d): %s" % (job.program, proc.pid, out))
    return job


# -- waiting and connecting ---------------------------------------------------

def wait_until_up(site, job, wait_secs=21600, log=print):
    """Poll until the job prints its CCS line; fills node/ip, records, returns job."""
    if site.scheduler == "local":
        t0 = time.time()
        while time.time() - t0 < wait_secs:
            try:
                with open(job.out) as f:
                    text = f.read()
                from ccsio import parse_server_line
                ip, port = parse_server_line(text)
                job.ip, job.node, job.port, job.state = ip, "localhost", port, "up"
                record(job)
                return job
            except (OSError, ValueError):
                pass
            if job.pid and not _pid_alive(job.pid):
                job.state = "ended"
                record(job)
                raise L.LaunchError("local job %s ended before the server came up; see %s" % (job.id, job.out))
            time.sleep(0.5)
        raise L.LaunchError("timed out waiting for %s" % job.id)
    try:
        ip, port, node = L.wait_for_server(site.ssh, job.id, job.out, wait_secs, log=log)
    except L.LaunchError as e:
        if "ended before the server came up" in str(e):
            status(site, job)                 # records the scheduler's final word (failed, cancelled, ...)
            if job.state in ("submitted", "running", "up"):
                job.state = "failed"
                record(job)
        raise
    job.ip, job.port, job.node, job.state = ip, port, node, "up"
    record(job)
    return job


def _port_free(port):
    import socket
    with socket.socket() as sk:
        try:
            sk.bind(("127.0.0.1", port))
            return True
        except OSError:
            return False


def connect(site, job, local_port=None):
    """Make the job's CCS port reachable; returns (host, port) for ccsio.
    The forward's local port is the job's port unless something on this
    machine already listens there (a local job, another forward), in which
    case the next free port above it is used."""
    if site.scheduler == "local":
        return "127.0.0.1", job.port
    if not job.node:
        raise L.LaunchError("job %s is %s and has no node yet; nothing to connect to" % (job.id, job.state))
    local_port = local_port or job.port
    while not _port_free(local_port) and local_port < job.port + 100:
        local_port += 1
    spec = L.forward_add(site.ssh, local_port, job.node, job.port)
    job.forward = spec
    record(job)
    return "127.0.0.1", local_port


def server(site, job, **kw):
    """connect() plus a ccsio.Server on the result, authenticated with the
    job's key when it has one. For scripts: ``s = jobs.server(site, job)``."""
    import ccsio
    host, port = connect(site, job)
    return ccsio.Server(host, port, key=job.key or None, **kw)


def disconnect(site, job):
    if site.scheduler != "local" and job.forward:
        L.forward_cancel(site.ssh)
        job.forward = ""
        record(job)


TERMINAL = ("completed", "failed", "cancelled", "timeout", "ended", "node_fail", "out_of_memory")


def status(site, job):
    """Refresh job.state from the scheduler (or the process)."""
    if site.scheduler == "local":
        alive = job.pid and _pid_alive(job.pid)
        job.state = job.state if (alive and job.state == "up") else ("running" if alive else "ended")
    else:
        text = L.ssh(site.ssh, "squeue -j %s -h -o '%%T %%N' 2>/dev/null; sacct -j %s -n -o State -P 2>/dev/null | head -1"
                     % (job.id, job.id), check=False).split()
        if text:
            st = text[0].lower().split("+")[0]        # "CANCELLED by 123" / "COMPLETED+" -> cancelled / completed
            if st == "by":
                st = "cancelled"
            job.state = "up" if (job.state == "up" and st == "running") else st
            if len(text) > 1 and st == "running":
                job.node = text[1]
    record(job)
    return job.state


def stop(site, job):
    disconnect(site, job)
    if site.scheduler == "local":
        if job.pid and _pid_alive(job.pid):
            os.kill(job.pid, 9)
    else:
        L.ssh(site.ssh, "scancel %s" % job.id, check=False)
    job.state = "cancelled"
    record(job)


def log_tail(site, job, lines=20):
    if site.scheduler == "local":
        try:
            with open(job.out) as f:
                return "".join(f.readlines()[-lines:])
        except OSError as e:
            return str(e)
    return L.ssh(site.ssh, "tail -n %d %s 2>&1" % (lines, job.out), check=False)


def _pid_alive(pid):
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False
