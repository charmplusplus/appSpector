#!/bin/bash
# Optional: charm4py (Python Charm++) for appSpector on a Slurm cluster.
# Run it ON A LOGIN NODE from the appSpector checkout, after cluster/setup.sh
# (it adds programs to the site file setup.sh wrote):
#
#   bash cluster/charm4py.sh delta mzu          # bash cluster/charm4py.sh SITE ALLOCATION
#
# What it does, all under $WORK/charm4py (WORK as in setup.sh):
#   - a Python venv (the cluster's Python module, see PYTHON_MODULE in
#     cluster/<site>.env) with Cython, NumPy, greenlet, patchelf, Pillow
#   - a Charm++ clone (charm4py target, reconverse, tracing) and a charm4py
#     clone, built with charm4py's setup.py (Charm++ PR #4063, charm4py PR #307)
#   - bin/c4p-python: the venv's python with the modules loaded, for batch jobs
#   - [programs] c4p_demo (apps/c4p_demo) and c4p_liveviz (charm4py's
#     examples/liveviz) in $WORK/site.ini, with the job option procs=pes:
#     a charm4py process runs ONE PE (several PEs per process crash at start)
# Optional overrides: APPSPECTOR_WORK, APPSPECTOR_JOBS (16),
#   C4P_CHARM_REF (Charm++ commit or branch, default recharm),
#   C4P_REF (charm4py commit or branch, default main),
#   C4P_CHECKOUT (an existing charm4py checkout to install instead of cloning).
#   (with C4P_CHECKOUT the liveviz fix below is reported, not applied: it is your checkout)
# Re-running skips what is built but checks out the refs again, so a changed C4P_REF or
# C4P_CHARM_REF takes effect; to rebuild Charm++ remove $WORK/charm4py/charm/$TRIPLET-charm4py
# (reconverse-linux-x86_64-charm4py), or all of $WORK/charm4py/charm.
set -eu
SITE=${1:-${SITE:-}}
ALLOC=${2:-${ALLOC:-}}
[ -n "$SITE" ] && [ -n "$ALLOC" ] || { echo "usage: bash cluster/charm4py.sh SITE ALLOCATION   (e.g. delta mzu)"; exit 1; }
REPO=$(cd "$(dirname "$0")/.." && pwd)
ENVFILE=$REPO/cluster/$SITE.env
[ -f "$ENVFILE" ] || { echo "no $ENVFILE"; exit 1; }
source "$ENVFILE"
WORK=${APPSPECTOR_WORK:-$WORK_DEFAULT}
JOBS=${APPSPECTOR_JOBS:-16}
C4P=$WORK/charm4py
CHARM_REF=${C4P_CHARM_REF:-recharm}
C4P_REF=${C4P_REF:-main}
TRIPLET=reconverse-linux-x86_64
step() { echo "== $(date +%H:%M:%S) $*"; }
mkdir -p "$C4P/bin"

{
  echo "# charm4py environment on $SITE (generated by cluster/charm4py.sh)"
  site_env
  [ -n "${PYTHON_MODULE:-}" ] && echo "module load $PYTHON_MODULE"
  echo "export PYTHONUNBUFFERED=1"
  echo "source $C4P/venv/bin/activate"
} > "$C4P/env.sh"
cat > "$C4P/bin/c4p-python" <<EOS
#!/bin/bash
# the charm4py venv's python with the cluster modules loaded (for batch jobs)
source $C4P/env.sh > /dev/null 2>&1
exec python -u "\$@"
EOS
chmod +x "$C4P/bin/c4p-python"

step "venv"
set +u; source "$C4P/env.sh" 2>/dev/null || true; set -u      # modules (the venv may not exist yet)
[ -x "$C4P/venv/bin/python" ] || python3 -m venv "$C4P/venv"
source "$C4P/venv/bin/activate"
python --version
pip -q install --upgrade pip setuptools wheel cython numpy greenlet patchelf pillow

step "Charm++ ($CHARM_REF) for the charm4py target"
# checkout and submodule update run every time (cheap): a rerun finishes a clone a failure
# interrupted, and follows a changed C4P_CHARM_REF (a changed ref needs a Charm++ rebuild:
# remove $C4P/charm/$TRIPLET-charm4py)
[ -d "$C4P/charm/.git" ] || git clone -q https://github.com/charmplusplus/charm.git "$C4P/charm"
(cd "$C4P/charm" && { git checkout -q "$CHARM_REF" 2>/dev/null || { git fetch -q origin && git checkout -q "$CHARM_REF"; }; } \
   && git submodule update -q --init contrib/reconverse && git log -1 --oneline)

step "charm4py ($C4P_REF)"
if [ -n "${C4P_CHECKOUT:-}" ]; then
  SRC=$C4P_CHECKOUT
  echo "using your checkout $SRC as it is (C4P_REF is not applied to it)"
  python "$REPO/cluster/c4p_setup.py" liveviz "$SRC" --check     # reports; never edits your checkout
else
  SRC=$C4P/src
  [ -d "$SRC/.git" ] || git clone -q https://github.com/charmplusplus/charm4py.git "$SRC"
  # our clone: undo the liveviz fix (if a previous run applied it) so the checkout can move, then
  # check out C4P_REF every time (it may have changed) and apply the fix again where it is needed
  (cd "$SRC" && { git checkout -q -- charm4py/liveviz.py 2>/dev/null || true; } && \
   { git checkout -q "$C4P_REF" 2>/dev/null || { git fetch -q origin && git checkout -q "$C4P_REF"; }; } && git log -1 --oneline)
  python "$REPO/cluster/c4p_setup.py" liveviz "$SRC"
fi
cd "$SRC"
# a copied checkout has no version metadata; setup.py then finds its version by importing the source tree
export PYTHONPATH=$SRC
export CHARM4PY_CHARM_DIR=$C4P/charm
export CHARM4PY_BUILD_TRIPLET=$TRIPLET
export CHARM4PY_CHARM_BUILD_DIR=$C4P/charm/$TRIPLET-charm4py
export CHARM_EXTRA_BUILD_OPTS=--enable-tracing CHARM_BUILD_PROCESSES=$JOBS
# GCC 14 (Delta's cc) turns these into errors; charm4py's generated Cython code needs them as warnings
export CFLAGS="${CFLAGS:-} -Wno-error=incompatible-pointer-types -Wno-error=implicit-function-declaration"
step "build and install (Charm++ the first time: 10-20 minutes; log $C4P/build.log)"
pip install --no-build-isolation -v . > "$C4P/build.log" 2>&1 || { echo "charm4py build failed; see $C4P/build.log"; tail -5 "$C4P/build.log"; exit 1; }
unset PYTHONPATH
cd /
"$C4P/bin/c4p-python" -c "import charm4py, os; print('charm4py', os.path.dirname(charm4py.__file__))"

step "programs in $WORK/site.ini"
SITEFILE=$WORK/site.ini
if [ -f "$SITEFILE" ]; then
  # into the existing [programs] section (added only if the file has none); entries you edited
  # (no "added by cluster/charm4py.sh" line above them) are kept
  python "$REPO/cluster/c4p_setup.py" programs "$SITEFILE" "$C4P" "$SRC"
else
  echo "no $SITEFILE (run cluster/setup.sh first); program lines to add by hand:"
  echo "  c4p_demo = {appspector}/apps/c4p_demo | $C4P/bin/c4p-python c4p_demo.py {args} +traceoff +pe {pes} ++server ++server-port {port} | --inject c4pInject | procs=pes"
fi

step "done"
echo "on your laptop:  python3 -m appspector, then  site fetch $SITE $SITE_SSH:$SITEFILE  (again, for the new programs)"
echo "  program c4p_demo / pes 4 / run / view"
