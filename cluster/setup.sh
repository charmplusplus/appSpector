#!/bin/bash
# Set up appSpector's server side on a Slurm cluster: a Charm++ (reconverse)
# build with tracing and liveViz, the example programs, the pfield demo,
# batch scripts and a site file for the laptop shell. Run it ON A LOGIN NODE
# of the cluster from a checkout of the appSpector repository:
#
#   SITE=delta ALLOC=mzu       bash cluster/setup.sh
#   SITE=anvil ALLOC=asc050025 bash cluster/setup.sh
#
# SITE picks cluster/<site>.env (modules, Slurm defaults); ALLOC is your
# allocation. Optional overrides, prefixed so they cannot collide with the
# cluster's own login environment (Anvil sets $WORK, for instance):
#   APPSPECTOR_WORK       work directory (default from the env file)
#   APPSPECTOR_BRANCH     charm branch (default recharm, which has every handler appSpector uses since charm PR #4071, 2026-10-23)
#   APPSPECTOR_PARTITION, APPSPECTOR_ACCOUNT, APPSPECTOR_MEM, APPSPECTOR_PORT (1234), APPSPECTOR_JOBS (16)
#   APPSPECTOR_CHARM      an existing Charm++ build directory to use instead of
#                         cloning and building one (a shared build for a class, e.g.
#                         /work/hdd/mzu/lkale/appspector/charm/reconverse-linux-x86_64):
#                         only the examples and pfield are built, in your own work directory
# Nothing depends on who runs it: paths come from $USER and these variables.
# Re-running skips the clone and the core build and rebuilds the rest.
set -eu
: "${SITE:?set SITE (delta, anvil)}"
: "${ALLOC:?set ALLOC to your allocation (Slurm account or its prefix)}"
REPO=$(cd "$(dirname "$0")/.." && pwd)
ENVFILE=$REPO/cluster/$SITE.env
[ -f "$ENVFILE" ] || { echo "no $ENVFILE; known sites: $(ls $REPO/cluster/*.env | xargs -n1 basename | sed 's/.env//' | tr '\n' ' ')"; exit 1; }
source "$ENVFILE"
WORK=${APPSPECTOR_WORK:-$WORK_DEFAULT}
BRANCH=${APPSPECTOR_BRANCH:-recharm}
PARTITION=${APPSPECTOR_PARTITION:-$PARTITION_DEFAULT}
ACCOUNT=${APPSPECTOR_ACCOUNT:-$ACCOUNT_DEFAULT}
JOBS=${APPSPECTOR_JOBS:-16}
PORT=${APPSPECTOR_PORT:-1234}
MEM=${APPSPECTOR_MEM-$MEM_DEFAULT}
step() { echo "== $(date +%H:%M:%S) $*"; }

mkdir -p "$WORK"
SHARED=${APPSPECTOR_CHARM:-}
CBUILD_PATH=${SHARED:-$WORK/charm/reconverse-linux-x86_64}
{
  echo "# appSpector environment on $SITE (generated by cluster/setup.sh)"
  site_env
  echo "export CBUILD=$CBUILD_PATH"
  echo 'export LD_LIBRARY_PATH=$CBUILD/lib:${LD_LIBRARY_PATH:-}'
} > "$WORK/env.sh"
set +u; source "$WORK/env.sh"; set -u

if [ -n "$SHARED" ]; then
  step "using the shared Charm++ build $SHARED"
  [ -x "$CBUILD/bin/charmc" ] || { echo "no charmc in $SHARED"; exit 1; }
  ls "$CBUILD/lib/libmoduleliveViz.a" > /dev/null || { echo "$SHARED has no liveViz (built without TARGET=LIBS)"; exit 1; }
  EXAMPLES=$WORK/examples
  mkdir -p "$EXAMPLES"
  # the shared tree is not ours to build in: copy the two example sources
  cp -r "$SHARED/../examples/converse/ccstest" "$EXAMPLES/" 2>/dev/null || cp -r "$(dirname "$SHARED")/examples/converse/ccstest" "$EXAMPLES/"
  cp -r "$(dirname "$SHARED")/examples/charm++/wave2d" "$EXAMPLES/"
  rm -f "$EXAMPLES"/*/*.o "$EXAMPLES"/*/*.decl.h "$EXAMPLES"/*/*.def.h
else
  step "charm clone ($BRANCH)"
  [ -d "$WORK/charm" ] || git clone -q --recurse-submodules -b "$BRANCH" https://github.com/charmplusplus/charm.git "$WORK/charm"
  cd "$WORK/charm" && git log -1 --oneline

  step "charm build (tracing on, about 6 minutes)"
  if [ ! -x "$CBUILD/bin/charmc" ]; then
    ./build charm++ reconverse-linux-x86_64 --with-production --enable-tracing -j$JOBS > "$WORK/charm-build.log" 2>&1 \
      || { echo "charm build failed; see $WORK/charm-build.log"; tail -5 "$WORK/charm-build.log"; exit 1; }
  fi
  step "ck-libs (liveViz)"
  cd "$CBUILD" && cmake -DTARGET=LIBS . > "$WORK/libs-build.log" 2>&1 && make -j$JOBS >> "$WORK/libs-build.log" 2>&1 \
    || { echo "LIBS build failed; see $WORK/libs-build.log"; tail -5 "$WORK/libs-build.log"; exit 1; }
  ls "$CBUILD/lib/libmoduleliveViz.a" "$CBUILD/lib/libtrace-utilization.a" > /dev/null
  EXAMPLES=$WORK/charm/examples
  EXAMPLES_CCS=$EXAMPLES/converse/ccstest
  EXAMPLES_WAVE=$EXAMPLES/charm++/wave2d
fi
EXAMPLES_CCS=${EXAMPLES_CCS:-$EXAMPLES/ccstest}
EXAMPLES_WAVE=${EXAMPLES_WAVE:-$EXAMPLES/wave2d}

step "examples"
cd "$EXAMPLES_CCS"
$CBUILD/bin/charmc -c server.C -language converse++ && $CBUILD/bin/charmc -o server server.o -language converse++
cd "$EXAMPLES_WAVE"
grep -q '#ifndef total_iterations' wave2d.C || sed -i 's/^#define total_iterations 5000$/#ifndef total_iterations\n#define total_iterations 5000\n#endif/' wave2d.C
make clean > /dev/null; make CHARMC="$CBUILD/bin/charmc -module liveViz -g" wave2d > "$WORK/wave2d-build.log" 2>&1
$CBUILD/bin/charmc -module liveViz -g -Dtotal_iterations=100000000 -c wave2d.C -o wave2d-demo.o >> "$WORK/wave2d-build.log" 2>&1
$CBUILD/bin/charmc -module liveViz -tracemode utilization -language charm++ -o wave2d-demo wave2d-demo.o >> "$WORK/wave2d-build.log" 2>&1

step "pfield"
make -C "$REPO/apps/pfield" clean > /dev/null; make -C "$REPO/apps/pfield" CHARM_HOME="$CBUILD" EXTRA_LDFLAGS= > "$WORK/pfield-build.log" 2>&1 \
  || { echo "pfield build failed; see $WORK/pfield-build.log"; tail -5 "$WORK/pfield-build.log"; exit 1; }

step "batch scripts (for appspector.launch; the shell generates its own)"
MEMLINE=""; [ -n "$MEM" ] && MEMLINE="#SBATCH --mem=$MEM"
sbatch_file() {  # name jobname workdir command
  cat > "$WORK/$1.sbatch" <<EOS
#!/bin/bash
#SBATCH -J $2
#SBATCH -A $ACCOUNT
#SBATCH -p $PARTITION
#SBATCH -N 1
#SBATCH --ntasks=2
#SBATCH --cpus-per-task=8
$MEMLINE
#SBATCH -t 00:10:00
#SBATCH -o $WORK/$1-%j.out
source $WORK/env.sh
ulimit -c 0
unset SLURM_CPUS_PER_TASK
export SLURM_CPU_BIND=none SRUN_CPU_BIND=none
cd $3
$(echo "$LAUNCHER" | sed 's/{procs}/2/; s/{cores_per_proc}/8/') $4
EOS
}
sbatch_file ccs    aspec-ccs  "$EXAMPLES_CCS"  "./server +pe 4 ++server ++server-port $PORT"
sbatch_file wave2d aspec-wave "$EXAMPLES_WAVE" "./wave2d-demo +pe 4 ++server ++server-port $PORT"
sbatch_file pfield aspec-pf   "$REPO/apps/pfield"                      "./pfield +pe 4 ++server ++server-port $PORT +balancer GreedyRefineLB"

step "site description for the laptop shell"
cat > "$WORK/site.ini" <<EOS
# appSpector site file for $SITE, written by cluster/setup.sh for $USER.
# On the laptop: python3 -m appspector, then  site fetch $SITE $SITE_SSH:$WORK/site.ini
[site]
scheduler = slurm
ssh = $SITE_SSH
work = $WORK
appspector = $REPO
env = {work}/env.sh
account = $ACCOUNT
partition = $PARTITION
cores_per_node = $CORES_PER_NODE
default_nodes = 1
default_procs_per_node = 2
default_pes = 4
walltime = 00:10:00
mem = $MEM
launcher = $LAUNCHER
port = $PORT
auth = yes

[programs]
pfield = {appspector}/apps/pfield | ./pfield {args} +pe {pes} ++server ++server-port {port} +balancer GreedyRefineLB
wave2d = $EXAMPLES_WAVE | ./wave2d-demo {args} +pe {pes} ++server ++server-port {port}
ccstest = $EXAMPLES_CCS | ./server {args} +pe {pes} ++server ++server-port {port}
EOS

step "done"
echo "work dir:  $WORK"
echo "site file: $WORK/site.ini"
echo "on your laptop:  python3 -m appspector"
echo "  site fetch $SITE $SITE_SSH:$WORK/site.ini     (once)"
echo "  site $SITE / program pfield -k 16 / pes 16 / run / view"
