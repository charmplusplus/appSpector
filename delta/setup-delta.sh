#!/bin/bash
# Set up appSpector's server side on NCSA Delta: a Charm++ (reconverse)
# build with tracing and liveViz, the example programs, the pfield demo,
# and batch scripts. Run it ON A DELTA LOGIN NODE from a checkout of the
# appSpector repository:
#
#   ALLOC=<your allocation, e.g. mzu> bash delta/setup-delta.sh
#
# Variables (all optional except ALLOC):
#   ALLOC      allocation short name; the account becomes $ALLOC-delta-cpu
#   WORK       work directory          (default /work/hdd/$ALLOC/$USER/appspector)
#   BRANCH     charm branch to build   (default appspector-delta; recharm once PR #4071 is merged)
#   PARTITION  Slurm partition         (default cpu-interactive)
#   ACCOUNT    Slurm account           (default $ALLOC-delta-cpu)
#   JOBS       make parallelism        (default 16)
#   PORT       the jobs' CCS port      (default 1234)
#
# Nothing here depends on who runs it: paths come from $USER and the
# variables above. Re-running skips the clone and rebuilds incrementally.
set -eu
: "${ALLOC:?set ALLOC to your allocation short name (the X in X-delta-cpu)}"
WORK=${WORK:-/work/hdd/$ALLOC/$USER/appspector}
BRANCH=${BRANCH:-appspector-delta}
PARTITION=${PARTITION:-cpu-interactive}
ACCOUNT=${ACCOUNT:-$ALLOC-delta-cpu}
JOBS=${JOBS:-16}
PORT=${PORT:-1234}
REPO=$(cd "$(dirname "$0")/.." && pwd)
step() { echo "== $(date +%H:%M:%S) $*"; }

mkdir -p "$WORK"
cat > "$WORK/env.sh" <<EOS
# appSpector environment on Delta (generated by delta/setup-delta.sh)
[ -z "\${LMOD_CMD:-}" ] && source /usr/share/lmod/lmod/init/bash
module load cmake/3.31.8
export FI_PROVIDER=cxi
export LCI_NETWORK_BACKENDS=ofi
export CBUILD=$WORK/charm/reconverse-linux-x86_64
export LD_LIBRARY_PATH=\$CBUILD/lib:\${LD_LIBRARY_PATH:-}
EOS
source "$WORK/env.sh"

step "charm clone ($BRANCH)"
if [ ! -d "$WORK/charm" ]; then
  git clone -q --recurse-submodules -b "$BRANCH" https://github.com/charmplusplus/charm.git "$WORK/charm"
fi
cd "$WORK/charm" && git log -1 --oneline

step "charm build (tracing on, about 6 minutes)"
if [ ! -x "$CBUILD/bin/charmc" ]; then
  ./build charm++ reconverse-linux-x86_64 --with-production --enable-tracing -j$JOBS > "$WORK/charm-build.log" 2>&1 \
    || { echo "charm build failed; see $WORK/charm-build.log"; tail -5 "$WORK/charm-build.log"; exit 1; }
fi
step "ck-libs (liveViz)"
cd "$CBUILD" && cmake -DTARGET=LIBS . > "$WORK/libs-build.log" 2>&1 && make -j$JOBS >> "$WORK/libs-build.log" 2>&1 \
  || { echo "LIBS build failed; see $WORK/libs-build.log"; tail -5 "$WORK/libs-build.log"; exit 1; }
ls "$CBUILD/lib/libmoduleliveViz.a" "$CBUILD/lib/libtrace-utilization.a" > /dev/null

step "examples"
cd "$WORK/charm/examples/converse/ccstest"
$CBUILD/bin/charmc -c server.C -language converse++ && $CBUILD/bin/charmc -o server server.o -language converse++
cd "$WORK/charm/examples/charm++/wave2d"
grep -q '#ifndef total_iterations' wave2d.C || sed -i 's/^#define total_iterations 5000$/#ifndef total_iterations\n#define total_iterations 5000\n#endif/' wave2d.C
make clean > /dev/null; make CHARMC="$CBUILD/bin/charmc -module liveViz -g" wave2d > "$WORK/wave2d-build.log" 2>&1
$CBUILD/bin/charmc -module liveViz -g -Dtotal_iterations=100000000 -c wave2d.C -o wave2d-demo.o >> "$WORK/wave2d-build.log" 2>&1
$CBUILD/bin/charmc -module liveViz -tracemode utilization -language charm++ -o wave2d-demo wave2d-demo.o >> "$WORK/wave2d-build.log" 2>&1

step "pfield"
make -C "$REPO/apps/pfield" clean > /dev/null; make -C "$REPO/apps/pfield" CHARM_HOME="$CBUILD" EXTRA_LDFLAGS= > "$WORK/pfield-build.log" 2>&1 \
  || { echo "pfield build failed; see $WORK/pfield-build.log"; tail -5 "$WORK/pfield-build.log"; exit 1; }

step "batch scripts"
sbatch_file() {  # name jobname workdir command
  cat > "$WORK/$1.sbatch" <<EOS
#!/bin/bash
#SBATCH -J $2
#SBATCH -A $ACCOUNT
#SBATCH -p $PARTITION
#SBATCH -N 1
#SBATCH --ntasks=2
#SBATCH --cpus-per-task=8
#SBATCH --mem=16g
#SBATCH -t 00:30:00
#SBATCH -o $WORK/$1-%j.out
source $WORK/env.sh
ulimit -c 0
unset SLURM_CPUS_PER_TASK
export SLURM_CPU_BIND=none SRUN_CPU_BIND=none
cd $3
stdbuf -o0 -e0 srun --mpi=pmix -n 2 -c 8 $4
EOS
}
sbatch_file ccs    aspec-ccs  "$WORK/charm/examples/converse/ccstest" "./server +pe 4 ++server ++server-port $PORT"
sbatch_file wave2d aspec-wave "$WORK/charm/examples/charm++/wave2d"   "./wave2d-demo +pe 4 ++server ++server-port $PORT"
sbatch_file pfield aspec-pf   "$REPO/apps/pfield"                      "./pfield +pe 4 ++server ++server-port $PORT +balancer GreedyRefineLB"

step "site description for the laptop shell"
cat > "$WORK/site.ini" <<EOS
# appSpector site file for Delta, written by delta/setup-delta.sh for $USER.
# On the laptop: python3 -m appspector, then  site fetch delta delta:$WORK/site.ini
[site]
scheduler = slurm
ssh = delta
work = $WORK
appspector = $REPO
env = {work}/env.sh
account = $ACCOUNT
partition = $PARTITION
cores_per_node = 128
default_nodes = 1
default_procs_per_node = 2
default_pes = 4
walltime = 00:30:00
mem = 16g
launcher = stdbuf -o0 -e0 srun --mpi=pmix -n {procs} -c {cores_per_proc}
port = $PORT

[programs]
pfield = {appspector}/apps/pfield | ./pfield {args} +pe {pes} ++server ++server-port {port} +balancer GreedyRefineLB
wave2d = {work}/charm/examples/charm++/wave2d | ./wave2d-demo {args} +pe {pes} ++server ++server-port {port}
ccstest = {work}/charm/examples/converse/ccstest | ./server {args} +pe {pes} ++server ++server-port {port}
EOS

step "done"
echo "work dir:  $WORK"
echo "batch:     $WORK/{ccs,wave2d,pfield}.sbatch  (account $ACCOUNT, partition $PARTITION)"
echo "site file: $WORK/site.ini"
echo "from your laptop (ssh master to Delta open), either:"
echo "  python3 -m appspector.launch run --site delta --sbatch $WORK/pfield.sbatch --port $PORT"
echo "or the shell:  python3 -m appspector"
echo "  site fetch delta delta:$WORK/site.ini     (once)"
echo "  site delta / program pfield -k 16 / pes 16 / run / view"
